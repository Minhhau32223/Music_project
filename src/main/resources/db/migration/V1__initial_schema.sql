CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    active BOOLEAN NOT NULL,
    role VARCHAR(255),
    avatar_url VARCHAR(255)
);
CREATE TABLE albums (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    image VARCHAR(255) NOT NULL,
    description VARCHAR(255) NOT NULL,
    bg_color VARCHAR(255) NOT NULL
);
CREATE TABLE artists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    bio VARCHAR(255) NOT NULL,
    profile_image VARCHAR(255) NOT NULL
);
CREATE TABLE songs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    file VARCHAR(255) NOT NULL,
    image VARCHAR(255) NOT NULL,
    lyrics VARCHAR(255) NOT NULL,
    duration VARCHAR(255) NOT NULL,
    play_count BIGINT NOT NULL,
    album_id BIGINT NOT NULL,
    artist_id BIGINT NOT NULL
);
CREATE TABLE playlists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255), image VARCHAR(255), user_id BIGINT
);
CREATE TABLE playlist_songs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playlist_id BIGINT, song_id BIGINT, added_at TIMESTAMP,
    UNIQUE (playlist_id, song_id)
);
CREATE TABLE favorite_songs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL, song_id BIGINT NOT NULL, created_at TIMESTAMP
);
CREATE TABLE artist_follows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL, artist_id BIGINT NOT NULL, followed_at TIMESTAMP,
    UNIQUE (user_id, artist_id)
);
CREATE TABLE recently_played (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT, song_id BIGINT, played_at TIMESTAMP
);
